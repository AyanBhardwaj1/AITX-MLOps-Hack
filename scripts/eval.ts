/**
 * Scores Runway's detectors against planted waste in seeded demo companies.
 * Usage: npm run eval            (prints a markdown table)
 *        npm run eval -- --write (also writes docs/eval-results.md)
 */
import { writeFileSync } from "node:fs";
import { scoreCategories, scoreFindings } from "../src/lib/eval/score";
import { analyze } from "../src/lib/pipeline";
import { generateDemoCompany } from "../src/lib/seed/demo-company";
import type { FindingKind } from "../src/lib/types";

const SEEDS = [1, 7, 42, 101, 2026];
const NOISE_LEVELS = ["clean", "noisy"] as const;
const KINDS: FindingKind[] = ["duplicate_tools", "price_creep", "zombie", "duplicate_charge"];

const mean = (xs: number[]) => xs.reduce((s, x) => s + x, 0) / xs.length;
const std = (xs: number[]) => Math.sqrt(mean(xs.map((x) => (x - mean(xs)) ** 2)));
const pct = (xs: number[]) => `${(mean(xs) * 100).toFixed(1)}% ± ${(std(xs) * 100).toFixed(1)}`;

interface Run {
  noise: string;
  seed: number;
  rows: number;
  precision: number;
  recall: number;
  dollarRecall: number;
  categoryAccuracy: number;
  ms: number;
  byKind: Record<FindingKind, { precision: number; recall: number }>;
  problems: string[];
}

const runs: Run[] = [];
for (const noise of NOISE_LEVELS) {
  for (const seed of SEEDS) {
    const demo = generateDemoCompany({ seed, noise });
    const start = performance.now();
    const result = analyze({ accounts: demo.accounts, transactions: demo.transactions, asOf: demo.asOf });
    const ms = performance.now() - start;
    const score = scoreFindings(result.findings, demo.truth);
    const cats = scoreCategories(result.txns, demo.categoryLabels);
    runs.push({
      noise,
      seed,
      rows: demo.transactions.length,
      precision: score.precision,
      recall: score.recall,
      dollarRecall: score.dollarRecall,
      categoryAccuracy: cats.accuracy,
      ms,
      byKind: Object.fromEntries(score.byKind.map((k) => [k.kind, { precision: k.precision, recall: k.recall }])) as Run["byKind"],
      problems: [
        ...score.missed.map((m) => `missed ${m.kind} [${m.vendorKeys.join(", ")}]`),
        ...score.unexpected.map((u) => `false positive ${u.kind} [${u.vendorKeys.join(", ")}]`),
      ],
    });
  }
}

const lines: string[] = [
  "# Detector eval results",
  "",
  `Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}: ${SEEDS.length} seeded companies × ${NOISE_LEVELS.length} descriptor noise levels (${runs.length} runs, ~${Math.round(mean(runs.map((r) => r.rows)))} transactions each).`,
  "Each company has planted waste plus negative controls (usage-based AWS/OpenAI growth, Slack + Zoom + Loom, AWS + Vercel) that must not be flagged.",
  "",
  "| Detector | Precision | Recall |",
  "|---|---|---|",
  ...KINDS.map((k) => `| ${k} | ${pct(runs.map((r) => r.byKind[k].precision))} | ${pct(runs.map((r) => r.byKind[k].recall))} |`),
  `| **All findings** | **${pct(runs.map((r) => r.precision))}** | **${pct(runs.map((r) => r.recall))}** |`,
  "",
  "| Metric | Clean descriptors | Noisy descriptors (SQ *, TST*, store #) |",
  "|---|---|---|",
  ...(
    [
      ["Dollar-weighted recall", (rs: Run[]) => pct(rs.map((r) => r.dollarRecall))],
      ["Vendor categorization accuracy (rules only, before LLM)", (rs: Run[]) => pct(rs.map((r) => r.categoryAccuracy))],
      ["Full analysis time (map + runway + detectors)", (rs: Run[]) => `${mean(rs.map((r) => r.ms)).toFixed(1)} ms`],
    ] as const
  ).map(([label, f]) => `| ${label} | ${f(runs.filter((r) => r.noise === "clean"))} | ${f(runs.filter((r) => r.noise === "noisy"))} |`),
];

const problems = runs.flatMap((r) => r.problems.map((p) => `- seed ${r.seed} (${r.noise}): ${p}`));
lines.push("", problems.length ? "## Errors\n" : "No missed items or false positives across all runs.", ...problems);

const report = lines.join("\n");
console.log(report);
if (process.argv.includes("--write")) {
  writeFileSync(new URL("../docs/eval-results.md", import.meta.url), `${report}\n`);
  console.log("\nWrote docs/eval-results.md");
}
